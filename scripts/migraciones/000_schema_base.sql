-- Schema del catálogo de re:Invent tal como estaba antes de las migraciones (DDL sacado del docker reinvent-pg).
-- Idempotente y sin prefijo de schema: se corre con search_path apuntando al schema destino (reinvent o uno de test).

CREATE TABLE IF NOT EXISTS empresa (
  id_empresa integer GENERATED BY DEFAULT AS IDENTITY,
  nombre     text NOT NULL,
  grupo      text,
  industria  text,
  es_amazon  boolean NOT NULL DEFAULT false,
  CONSTRAINT pk_empresa PRIMARY KEY (id_empresa),
  CONSTRAINT uq_empresa_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS empresa_alias (
  alias      text NOT NULL,
  id_empresa integer,
  regla      text NOT NULL,
  CONSTRAINT pk_empresa_alias PRIMARY KEY (alias),
  CONSTRAINT fk_empresa_alias__empresa FOREIGN KEY (id_empresa) REFERENCES empresa (id_empresa)
);

CREATE TABLE IF NOT EXISTS speaker (
  id_speaker   integer GENERATED BY DEFAULT AS IDENTITY,
  nombre       text NOT NULL,
  apodo        text,
  nombre_clave text NOT NULL,
  CONSTRAINT pk_speaker PRIMARY KEY (id_speaker),
  CONSTRAINT uq_speaker_nombre_clave UNIQUE (nombre_clave)
);

CREATE TABLE IF NOT EXISTS speaker_perfil (
  id_speaker           integer NOT NULL,
  crustdata_person_id  bigint,
  encontrado           boolean NOT NULL,
  verificar            boolean,
  cargo_actual         text,
  empresa_actual       text,
  seniority            text,
  cargo_desde          date,
  industria_empresa    text,
  headline             text,
  ubicacion            text,
  linkedin_url         text,
  github_url           text,
  x_handle             text,
  skills               text[],
  otros_roles_actuales text,
  trayectoria          jsonb,
  educacion            jsonb,
  fuente               text NOT NULL,
  fecha_consulta       date NOT NULL,
  calidad_match        text,
  CONSTRAINT pk_speaker_perfil PRIMARY KEY (id_speaker),
  CONSTRAINT fk_speaker_perfil__speaker FOREIGN KEY (id_speaker) REFERENCES speaker (id_speaker) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS speech (
  id_speech         text NOT NULL,
  titulo            text NOT NULL,
  tipo              text NOT NULL,
  nivel             smallint,
  topicos           text[] NOT NULL DEFAULT '{}',
  servicios         text[] NOT NULL DEFAULT '{}',
  area_interes      text,
  formato           text,
  es_lanzamiento    boolean NOT NULL DEFAULT false,
  resumen           text,
  speakers_original text,
  CONSTRAINT pk_speech PRIMARY KEY (id_speech)
);

CREATE TABLE IF NOT EXISTS speech_horario (
  codigo      text NOT NULL,
  id_speech   text NOT NULL,
  fecha       date NOT NULL,
  hora_inicio time NOT NULL,
  sede        text NOT NULL,
  sala        text,
  cupo        integer,
  walk_up     boolean NOT NULL DEFAULT false,
  CONSTRAINT pk_speech_horario PRIMARY KEY (codigo),
  CONSTRAINT fk_speech_horario__speech FOREIGN KEY (id_speech) REFERENCES speech (id_speech) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS speech_speaker (
  id_speech        text NOT NULL,
  id_speaker       integer NOT NULL,
  id_empresa       integer,
  orden            smallint NOT NULL,
  empresa_original text,
  CONSTRAINT pk_speech_speaker PRIMARY KEY (id_speech, id_speaker),
  CONSTRAINT fk_speech_speaker__speech FOREIGN KEY (id_speech) REFERENCES speech (id_speech) ON DELETE CASCADE,
  CONSTRAINT fk_speech_speaker__speaker FOREIGN KEY (id_speaker) REFERENCES speaker (id_speaker),
  CONSTRAINT fk_speech_speaker__empresa FOREIGN KEY (id_empresa) REFERENCES empresa (id_empresa)
);

CREATE INDEX IF NOT EXISTS ix_empresa__industria ON empresa (industria);
CREATE INDEX IF NOT EXISTS ix_speech__servicios ON speech USING gin (servicios);
CREATE INDEX IF NOT EXISTS ix_speech_horario__fecha ON speech_horario (fecha, hora_inicio);
CREATE INDEX IF NOT EXISTS ix_speech_horario__speech ON speech_horario (id_speech);
CREATE INDEX IF NOT EXISTS ix_speech_speaker__empresa ON speech_speaker (id_empresa);
CREATE INDEX IF NOT EXISTS ix_speech_speaker__speaker ON speech_speaker (id_speaker);

CREATE OR REPLACE VIEW v_speaker_empresa_principal AS
SELECT DISTINCT ON (ss.id_speaker) ss.id_speaker, sk.nombre AS speaker, e.id_empresa, e.nombre AS empresa, e.es_amazon,
       count(*) AS speeches_con_esa_empresa
FROM speech_speaker ss
JOIN speaker sk ON sk.id_speaker = ss.id_speaker
JOIN empresa e ON e.id_empresa = ss.id_empresa
GROUP BY ss.id_speaker, sk.nombre, e.id_empresa, e.nombre, e.es_amazon
ORDER BY ss.id_speaker, count(*) DESC, e.es_amazon, e.nombre;

CREATE OR REPLACE VIEW v_speaker_ficha AS
SELECT sk.id_speaker, sk.nombre, sk.apodo, pr.empresa AS empresa_catalogo, pr.es_amazon, e.industria AS industria_catalogo,
       p.encontrado, p.calidad_match, p.verificar,
       ok.cargo_actual, ok.empresa_actual, ok.seniority, ok.cargo_desde, ok.headline, ok.ubicacion, ok.linkedin_url,
       ok.github_url, ok.x_handle, ok.skills, ok.trayectoria, ok.educacion,
       (SELECT string_agg(ss.id_speech || ' - ' || s.titulo, E'\n' ORDER BY ss.id_speech)
          FROM speech_speaker ss JOIN speech s USING (id_speech)
         WHERE ss.id_speaker = sk.id_speaker) AS speeches
FROM speaker sk
LEFT JOIN v_speaker_empresa_principal pr ON pr.id_speaker = sk.id_speaker
LEFT JOIN empresa e ON e.id_empresa = pr.id_empresa
LEFT JOIN speaker_perfil p ON p.id_speaker = sk.id_speaker
LEFT JOIN speaker_perfil ok ON ok.id_speaker = sk.id_speaker AND ok.calidad_match IN ('confiable', 'revisar');

CREATE OR REPLACE VIEW v_speech_con_cliente AS
SELECT sp.id_speech, sp.titulo, sp.tipo, sp.nivel,
       string_agg(DISTINCT e.nombre, ', ' ORDER BY e.nombre) AS empresas_cliente,
       string_agg(DISTINCT e.industria, ', ' ORDER BY e.industria) AS industrias_cliente
FROM speech sp
JOIN speech_speaker ss ON ss.id_speech = sp.id_speech
JOIN empresa e ON e.id_empresa = ss.id_empresa
WHERE NOT e.es_amazon
GROUP BY sp.id_speech, sp.titulo, sp.tipo, sp.nivel;

CREATE OR REPLACE VIEW v_speech_speaker_empresa AS
SELECT sp.id_speech, sp.titulo, sp.tipo, sp.nivel, sk.id_speaker, sk.nombre AS speaker, sk.apodo,
       e.id_empresa, e.nombre AS empresa, e.grupo, e.industria, e.es_amazon, ss.orden
FROM speech_speaker ss
JOIN speech sp ON sp.id_speech = ss.id_speech
JOIN speaker sk ON sk.id_speaker = ss.id_speaker
LEFT JOIN empresa e ON e.id_empresa = ss.id_empresa;
